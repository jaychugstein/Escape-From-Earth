# Builds the FX flash data for Escape From Earth from the art files, and writes fxdata.h for the sketch.
# Run the art scripts first (title_anim.py, glorb.py, glorb_happy.py, controls.py, menu_art.py, scorebg.py,
# mother.py, ufo_rot.py, level/gen_level2.py), then:  python3 fxpack.py
import os, sys, numpy as np
ART = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ART, '..', 'EscapeFromEarth')
def screen(npy):                                    # 128x64 picture -> 1024 bytes in Arduboy screen order
    f = np.load(os.path.join(ART, npy))
    return bytes(sum(int(f[p * 8 + k, x] > 0) << k for k in range(8)) for p in range(8) for x in range(128))
def raw(name): return open(os.path.join(ART, name), 'rb').read()
level = raw('level/level.bin'); LW = len(level) // 16
parts = [
    ('FX_TITLE',    b''.join(screen('title_f%d.npy' % t) for t in range(8)), 'title screen, 8 animation frames'),
    ('FX_GLORB',    screen('glorb.npy'),        'Glorb at the start (bonked)'),
    ('FX_GLORB2',   screen('glorb_happy.npy'),  'happy Glorb for the win'),
    ('FX_CONTROLS', screen('controls.npy'),     'controls screen'),
    ('FX_MENU',     raw('menu.bin'),            'sound screen: ON a, ON b, OFF a, OFF b'),
    ('FX_SCOREBG',  raw('scorebg.bin'),         'end screen frame'),
    ('FX_MOTHER',   raw('mother.bin'),          'mothership, masked bitmap'),
    ('FX_UFOROT',   raw('ufo_rot.bin'),         'saucer at 64 angles x 2 light frames, 24x24 masked'),
    ('FX_LVL',      level,                      'the course: 8 rows of LVL_W columns, picture byte + solid byte each'),
]
data = bytearray(); hdr = []
for name, blob, note in parts:
    while len(data) % 256: data.append(0)
    hdr.append('constexpr uint24_t %-11s = 0x%06X;   // %s' % (name, len(data), note))
    data += blob
while len(data) % 256: data.append(0xFF)
page = 0x10000 - len(data) // 256
os.makedirs(OUT, exist_ok=True)
os.makedirs(os.path.join(OUT, 'fxdata'), exist_ok=True)
open(os.path.join(OUT, 'fxdata', 'fxdata.bin'), 'wb').write(data)
h = '// generated by art/fxpack.py - do not edit\n#pragma once\n#include <ArduboyFX.h>\n'
h += 'constexpr uint16_t FX_DATA_PAGE = 0x%04X;   // %d bytes of FX data\n' % (page, len(data))
h += '\n'.join(hdr) + '\nconstexpr int16_t LVL_W = %d;\n' % LW
open(os.path.join(OUT, 'fxdata.h'), 'w').write(h)
print(h)
